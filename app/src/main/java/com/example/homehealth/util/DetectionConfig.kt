package com.example.homehealth.util

/**
 * 异常检测的可调参数集中处。
 *
 * **为什么集中**：这些值直接决定「你会被什么报警、多久报一次、报得多敏感」。
 * 散落在各 UseCase / Repository 里时，调参找不到、改一个忘一个。
 * 每个值都写明取值理由 —— 没有理由的魔数不该放在这里。
 *
 * 与 [HealthTypes.TREND_THRESHOLDS] 的分工：每个指标的「有意义变化幅度」与指标本身强相关
 * （血糖 1.0 与尿酸 60 不是一个量级），因此留在指标字典里；本对象只放与具体指标无关的
 * 全局窗口与样本数门槛。
 */
object DetectionConfig {

    /** 一天的毫秒数（趋势跨度换算用） */
    const val DAY_MS = 24L * 60 * 60 * 1000

    /**
     * 同一 type+title 的预警去重窗口。
     *
     * 取值理由：窗口太短，用户读掉预警后会被重复骚扰；太长，症状复发又迟迟不报。
     * 7 天 ≈ 一次复诊周期。注意窗口内**严重度升级不受此限制**（见 `DetectAnomaliesUseCase`），
     * 否则病情恶化会被这条去重规则吞掉。
     */
    const val DEDUPE_WINDOW_MS = 7L * DAY_MS

    /**
     * 趋势规则的时间窗：最近三次读数跨度超过它，就不构成「持续」趋势。
     *
     * 取值理由：三次读数跨两年与跨一周不是同一件事，前者说成"持续上升"是误导。
     * 180 天接近体检常见复查间隔的上限。
     */
    const val TREND_MAX_SPAN_MS = 180L * DAY_MS

    /**
     * 个体基线所需的最少历史样本数。
     *
     * 取值理由：样本太少时中位数没有统计意义，等于拿两三个点硬编一个"基线"出来，
     * 反而会制造假警报。
     */
    const val BASELINE_MIN_SAMPLES = 5
}
